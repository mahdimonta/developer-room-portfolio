"""Build every generated asset and write room-layout.json.

Run from the project root:  npm run assets:build
All sprites are original work generated by this script (CC0-style, no
third-party artwork), which is why the room has one consistent palette,
one isometric angle and one light direction.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import gen_room          # noqa: E402
import gen_props         # noqa: E402
import gen_character     # noqa: E402
import gen_cat           # noqa: E402
import gen_effects       # noqa: E402
import stage             # noqa: E402


def main():
    print("== room shell ==")
    gen_room.main()
    print("== props ==")
    gen_props.main()
    print("== character ==")
    gen_character.main()
    print("== cat ==")
    gen_cat.main()
    print("== effects ==")
    gen_effects.main()
    p = stage.write_layout()
    n_s = len(stage.LAYOUT["sprites"])
    n_a = len(stage.LAYOUT["anims"])
    n_q = len(stage.LAYOUT.get("quads", {}))
    print(f"\nlayout -> {p}")
    print(f"{n_s} sprite layers, {n_a} animations, {n_q} surfaces")
    total = 0
    for root, _, files in os.walk(os.path.join(HERE, "..", "public", "assets")):
        for f in files:
            if f.endswith(".png"):
                total += os.path.getsize(os.path.join(root, f))
    print(f"generated PNG payload: {total/1024:.0f} KB")


if __name__ == "__main__":
    main()
